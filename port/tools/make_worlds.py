#!/usr/bin/env python3
"""Kid Bunka's 48 worlds for VIBE FM (0.19):  python3 tools/make_worlds.py  ->  garden-worlds-data.inc

Reads the worlds of the Trimui Brick port (tools/worlds/worlds.txt) through a copy of the MPC's converter
(tools/worlds/convert.py: parse, convert). VIBE FM keeps what it has: the Biome, tempo, macros, the engine settings and the eight texture /
space lanes (the MPC's mapping of SHIMMER -> BLOOM and CLOUD / PARTICLES / SEEDS -> GRAIN included). The Brick's
Sound Lab and the MPC's POLY layer have no counterpart here."""
import importlib.util, os
HERE = os.path.dirname(os.path.abspath(__file__))
# (0.31) self-contained: tools/worlds/ holds a copy of the worlds (worlds.txt) and of the MPC's converter (convert.py)
spec = importlib.util.spec_from_file_location("mpc_worlds", os.path.join(HERE, "worlds", "convert.py"))
mw = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mw)
worlds = mw.parse()
families = []
for w in worlds:
    if w["family"] not in families: families.append(w["family"])
def cs(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["/* Generated by tools/make_worlds.py from the Trimui Brick port's worlds (through MPC/tools/make_worlds.py).",
       " * Do not edit by hand. Kid Bunka's worlds: Biome, tempo, macros (-1 keep), engine settings, lanes (-1 none). */",
       "static const char *const world_families[] = {" + ", ".join(cs(f) for f in families) + "};",
       "static const world_spec worlds[] = {"]
for w in worlds:
    engine, lanes = mw.convert(w)[:2]
    macros = w["macros"] or [-1, -1, -1, -1]
    eng = ", ".join("{%s,%d,%d}" % e for e in engine[:12]) or "{0,0,0}"
    out.append("    {%d, %s, %s, %d, %d, {%s}, %d, {%s}, {%s}}," % (families.index(w["family"]), cs(w["name"]), cs(w["story"]),
               w["biome"], w["tempo"] or 0, ",".join(str(m) for m in macros), min(len(engine), 12), eng, ",".join(str(x) for x in lanes)))
out.append("};")
out.append("enum { WORLDS = %d, WORLD_FAMILIES = %d };" % (len(worlds), len(families)))
open(os.path.join(HERE, "..", "garden-worlds-data.inc"), "w").write("\n".join(out) + "\n")
print(len(worlds), "worlds,", len(families), "families")
